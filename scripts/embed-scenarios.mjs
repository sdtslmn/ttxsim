// Copies scenarios/*.yaml into a TypeScript module so the CLI and the
// browser build ship the same scenario set without reading files at runtime.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "scenarios");
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".yaml"))
  .sort();
const entries = files.map((file) => ({ file, source: readFileSync(join(dir, file), "utf8") }));
const out = join(root, "src", "core", "generated");
mkdirSync(out, { recursive: true });
writeFileSync(
  join(out, "scenarios.ts"),
  `// Generated by scripts/embed-scenarios.mjs. Do not edit.\nexport const SCENARIO_FILES: { file: string; source: string }[] = ${JSON.stringify(entries, null, 2)};\n`,
);
console.log(`embedded ${entries.length} scenario file${entries.length === 1 ? "" : "s"}`);

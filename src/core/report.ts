export function grade(d: Debrief, s: Scenario): string {
  if (d.failed) return "Not passed: the incident got away from you";
  if (d.score >= 90) return "Excellent";
  if (d.score >= s.passMark) return "Passed";
  return "Not passed";
}

/** A Markdown after-action report for one finished run. */
export function reportMarkdown(sim: Sim, when = new Date()): string {
  const s = sim.scenario;
  const d = sim.debrief();
  const lines: string[] = [];
  lines.push(`# After-action report: ${s.title}`);
  lines.push("");
  lines.push(`Generated by TTXSim on ${when.toISOString().slice(0, 10)}. This is a training exercise; the organization and events are fictional.`);
  lines.push("");
  lines.push("## Summary");
  lines.push("");
  lines.push(`- **Scenario:** ${s.title} (${s.org}${s.sector ? `, ${s.sector}` : ""})`);
  lines.push(`- **Your role:** ${s.role}`);
  lines.push(`- **Result:** ${grade(d, s)}, score ${d.score}% (pass mark ${s.passMark}%)`);
  lines.push(`- **Exercise time used:** ${duration(d.time)}, ended at ${clockLabel(s, d.time)}`);
  lines.push(`- **Actions taken:** ${d.actionsTaken}`);
  const setup = tailorSummary(s);
  if (setup.length) lines.push(`- **Setup:** ${setup.map((t) => `${t.label}: ${t.value}`).join("; ")}`);
  lines.push("");
  lines.push(d.endText);
  lines.push("");
  lines.push("## Objectives");
  lines.push("");
  for (const o of d.objectives) {
    lines.push(`- ${o.passed ? "[x]" : "[ ]"} **${o.objective.text}** (weight ${o.objective.weight})`);
    lines.push(`  ${o.passed ? o.objective.hit : o.objective.miss}`);
  }
  lines.push("");
  if (d.meters.length) {
    lines.push("## Where things ended");
    lines.push("");
    lines.push("| Measure | Start | End | Better when |");
    lines.push("| --- | ---: | ---: | --- |");
    for (const m of d.meters) lines.push(`| ${m.label} | ${m.start} | ${m.value} | ${m.good === "high" ? "higher" : "lower"} |`);
    lines.push("");
  }
  const status = sim.statusNow();
  if (status.length) {
    lines.push("| Status | At the end |");
    lines.push("| --- | --- |");
    for (const st of status) lines.push(`| ${st.item.label} | ${st.text} |`);
    lines.push("");
  }
  if (s.phases.length) {
    lines.push("## Discussion notes");
    lines.push("");
    for (const ph of s.phases) {
      const reached = sim.phases.find((x) => x.phase.id === ph.id);
      lines.push(`### ${ph.title}${reached ? ` (${clockLabel(s, reached.time)})` : " (not reached)"}`);
      lines.push("");
      for (const q of ph.questions) lines.push(`- ${q}`);
      lines.push("");
      lines.push(sim.notes[ph.id] ? `**Notes:** ${sim.notes[ph.id].trim()}` : "_No notes recorded._");
      lines.push("");
    }
  }
  lines.push(...teamMarkdown(sim));
  if (s.attack.length) {
    lines.push(attackMarkdown(s));
  }
  lines.push("## Response activity by NIST CSF 2.0 category");
  lines.push("");
  lines.push("| Category | Actions |");
  lines.push("| --- | ---: |");
  const byCsf = new Map<string, number>();
  for (const g of GROUPS) byCsf.set(GROUP_INFO[g].csf, (byCsf.get(GROUP_INFO[g].csf) ?? 0) + d.groups[g]);
  for (const [csf, n] of byCsf) lines.push(`| ${csf} | ${n} |`);
  lines.push("");
  const flow = buildFlow(s);
  const path = overlayPath(flow, sim);
  const keySteps = flow.steps.filter((x) => x.kind === "action");
  if (keySteps.length) {
    lines.push("## Your path against the model path");
    lines.push("");
    lines.push("Steps from the scenario's model response, and whether you took them:");
    lines.push("");
    for (const step of keySteps) lines.push(`- ${path.done.has(step.id) ? "[x]" : "[ ]"} ${step.title}`);
    const happened = flow.steps.flatMap((x) => x.branches).filter((b) => path.happened.has(b.id));
    if (happened.length) {
      lines.push("");
      lines.push("Things that went wrong in your run:");
      lines.push("");
      for (const b of happened) lines.push(`- ${b.kind === "trap" ? "You chose" : "It happened"}: ${b.title}`);
    }
    lines.push("");
  }
  if (d.lessons.length) {
    lines.push("## Notes on your decisions");
    lines.push("");
    for (const l of d.lessons) lines.push(`- **${l.action.label}:** ${l.text}`);
    lines.push("");
  }
  lines.push("## Timeline");
  lines.push("");
  lines.push("| Time | Event |");
  lines.push("| --- | --- |");
  for (const e of sim.log) {
    const what =
      e.kind === "inject" ? `Received: ${e.title}` : e.kind === "action" ? `Action: ${e.title}` : e.kind === "end" ? e.title : e.title;
    lines.push(`| ${clockLabel(s, e.time)} | ${what.replace(/\|/g, "/")} |`);
  }
  lines.push("");
  if (s.references.length) {
    lines.push("## Further reading");
    lines.push("");
    for (const r of s.references) lines.push(`- ${r}`);
    lines.push("");
  }
  lines.push("## Hot wash questions for your team");
  lines.push("");
  lines.push("- What did we know at each decision point, and what did we assume?");
  lines.push("- Which decision would we make differently, and what would have told us sooner?");
  lines.push("- Does our real incident response plan cover this situation? Who owns each gap?");
  lines.push("");
  return lines.join("\n");
}

const cell = (t: string) => t.replace(/\s+/g, " ").replace(/\|/g, "/").trim();

/** Team roster, decisions with votes and rationale, and facilitator injects. Empty for solo play. */
export function teamMarkdown(sim: Sim): string[] {
  const s = sim.scenario;
  const out: string[] = [];
  if (sim.team.length) {
    out.push("## Team");
    out.push("");
    out.push("| Seat | Name |");
    out.push("| --- | --- |");
    for (const m of sim.team) out.push(`| ${cell(memberLabel({ role: m.role, name: "" }))} | ${cell(m.name) || "_not named_"} |`);
    out.push("");
  }
  if (sim.decisions.length) {
    out.push("## Team decisions");
    out.push("");
    out.push("| Time | Decision | Decided by | Vote | Why |");
    out.push("| --- | --- | --- | --- | --- |");
    for (const d of sim.decisions) {
      const vote = d.vote ? d.vote.map((o) => `${o.label}: ${o.votes}`).join("; ") : "";
      out.push(`| ${clockLabel(s, d.time)} | ${cell(d.label)} | ${cell(d.by ?? "")} | ${cell(vote)} | ${cell(d.rationale ?? "")} |`);
    }
    out.push("");
    const split = sim.decisions.filter((d) => d.vote && d.vote.filter((o) => o.votes > 0).length > 1);
    if (split.length) {
      out.push(`${split.length} decision${split.length === 1 ? " was" : "s were"} not unanimous. These are good places to start the hot wash.`);
      out.push("");
    }
  }
  if (sim.pushed.length) {
    out.push("## Injects pushed by the facilitator");
    out.push("");
    for (const p of sim.pushed) out.push(`- ${clockLabel(s, p.time)}: ${p.subject}${p.custom ? " (written on the day)" : ""}`);
    out.push("");
  }
  return out;
}

